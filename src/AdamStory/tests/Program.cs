using AlienStory;

static void Check(bool ok, string msg) { if (!ok) throw new Exception(msg); }
Check(StoryText.Hunger[0][1].Contains("參宿二"), "wallet names 參宿二");
Check(StoryText.Hunger[1][1].Contains("阿里嘎豆") && StoryText.Hunger[1][1].Contains("應該是你們的語言沒錯"), "requested thank-you line");
Check(StoryText.Introduction[^1] == "我叫亞當，謝謝你的幫助。", "requested name reveal line");
var reject = new StoryState();
Check(!StoryCore.IsEligible(reject, 22) && StoryCore.IsEligible(reject, 23), "formal story starts no earlier than day 23");
for (int visit = 1; visit <= 4; visit++) {
    int day = visit + 22;
    Check(StoryCore.IsEligible(reject, day), "eligible refusal " + visit);
    Check(StoryCore.Apply(reject, StoryAction.RefuseAid, day, visit), "refusal accepted " + visit);
    Check(!StoryCore.Apply(reject, StoryAction.RefuseAid, day, visit), "same visit counted twice");
    Check(reject.refusals == visit, "refusal count");
}
Check(reject.stage == Stage.Judgment && !StoryCore.IsEligible(reject, 26) && StoryCore.IsEligible(reject, 27), "god visits next day");
Check(!StoryCore.Apply(reject, StoryAction.Apologize, 26, 5), "judgment too early");
Check(StoryCore.Apply(reject, StoryAction.Apologize, 27, 5), "apology accepted");
Check(reject.restitutionDeadline == 34 && !StoryCore.Apply(reject, StoryAction.ExpireRestitution, 34, 6), "seven-day inclusive deadline");
Check(StoryCore.Apply(reject, StoryAction.DeliverRestitution, 34, 6) && reject.stage == Stage.Introduction, "redemption at deadline");
var timeout = new StoryState { stage = Stage.Restitution, restitutionDeadline = 34 };
Check(!StoryCore.Apply(timeout, StoryAction.DeliverRestitution, 35, 1), "late delivery rejected");
Check(StoryCore.Apply(timeout, StoryAction.ExpireRestitution, 35, 1) && timeout.stage == Stage.BadEnding, "failed restitution");
foreach (var action in Enum.GetValues<StoryAction>()) Check(!StoryCore.Apply(timeout, action, 100, 100), "bad ending reopened");
var rescue = new StoryState();
Check(!rescue.revealed, "name hidden before introduction");
Check(StoryCore.Apply(rescue, StoryAction.RefuseAid, 23, 1), "first refusal");
Check(StoryCore.Apply(rescue, StoryAction.DeliverAid, 24, 2), "aid accepted");
Check(!rescue.revealed && rescue.stage == Stage.Introduction, "name changed too early");
Check(StoryCore.Apply(rescue, StoryAction.FinishIntroduction, 24, 2), "introduction");
Check(rescue.revealed && !StoryCore.IsEligible(rescue, 25) && StoryCore.IsEligible(rescue, 26), "recovery timing");
Check(StoryCore.Apply(rescue, StoryAction.BeginScavenging, 26, 3), "scavenger intro");
Check(!StoryCore.Apply(rescue, StoryAction.DeliverElectronics, 28, 4), "early electronics");
Check(StoryCore.Apply(rescue, StoryAction.EndScrapVisit, 28, 4), "scrap visit");
Check(rescue.scavengerVisits == 1, "scrap visit increments alternating mode");
Check(rescue.partsReadyDay == 29 && StoryCore.IsEligible(rescue, 30), "three days and repeat");
Check(StoryCore.Apply(rescue, StoryAction.DeliverElectronics, 42, 5), "late electronics still accepted");
Check(!StoryCore.Apply(rescue, StoryAction.DeliverBattery, 43, 6), "battery too early");
Check(StoryCore.Apply(rescue, StoryAction.DeliverBattery, 44, 6), "battery accepted");
Check(StoryCore.Apply(rescue, StoryAction.Stay, 44, 6), "stay ending");
Check(!StoryCore.Apply(rescue, StoryAction.Leave, 44, 6), "mutually exclusive ending");
Check(!StoryCore.CanClaimOre(2, 3, 10) && !StoryCore.CanClaimOre(3, 3, 9), "ore day and capacity boundaries");
Check(StoryCore.CanClaimOre(3, 3, 10) && StoryCore.NextChargeDay(3) == 6, "ore ready and recharge");
var depart = new StoryState { stage = Stage.Decision, revealed = true };
Check(StoryCore.Apply(depart, StoryAction.Leave, 10, 1) && depart.stage == Stage.Departed, "space ending");
var food = new OfferedItem { Id = "meal", Count = 1, IsFood = true, KcalPerUnit = 99 };
var water = new OfferedItem { Id = "water", Count = 1, IsWater = true };
Check(TradeRules.Aid(new[] { food }) && TradeRules.Aid(new[] { water }), "either food or water alone suffices");
Check(!TradeRules.Aid(Array.Empty<OfferedItem>()) && !TradeRules.Aid(new[] { food, water }), "empty and unintended extra item rejected");
Check(!TradeRules.Restitution(new[] { food }), "99 kcal is insufficient");
Check(TradeRules.Restitution(new[] { food, new OfferedItem { Id = "meal2", Count = 1, IsFood = true, KcalPerUnit = 1 } }), "100 kcal succeeds");
Check(TradeRules.Restitution(new[] { new OfferedItem { Id = "meal", Count = 2, IsFood = true, KcalPerUnit = 50 } }), "stack caloric sum");
Check(!TradeRules.Restitution(new[] { new OfferedItem { Id = "meal", Count = 1, IsFood = true, KcalPerUnit = 100 }, water }), "extra non-food cannot be accidentally donated");
Check(!TradeRules.Restitution(new[] { water }) && !TradeRules.Restitution(new[] { new OfferedItem { Count = -1, IsFood = true, KcalPerUnit = 100 } }), "invalid food rejected");
Check(TradeRules.Electronics(new[] { new OfferedItem { Id = "common_electronic", Count = 3 } }), "electronics amount");
Check(!TradeRules.Electronics(new[] { new OfferedItem { Id = "common_electronic", Count = 4 } }), "do not consume excess electronics");
Check(TradeRules.Battery(new[] { new OfferedItem { Id = "energy_credit_breeder", Count = 1 } }), "recharging battery");
Check(PreviewPlanner.Missing(0) == PreviewPlanner.All && !PreviewPlanner.IsComplete(0), "queue all three previews");
var previews = PreviewPlanner.Arrived(0, PreviewPlanner.Dog);
previews = PreviewPlanner.Arrived(previews, PreviewPlanner.Adam);
Check(!PreviewPlanner.IsComplete(previews) && (PreviewPlanner.Missing(previews) & PreviewPlanner.Hunger1) != 0, "unseen preview retried");
foreach (int role in new[] { PreviewPlanner.Hunger1, PreviewPlanner.Hunger2, PreviewPlanner.Hunger3, PreviewPlanner.Scavenger, PreviewPlanner.God }) previews = PreviewPlanner.Arrived(previews, role);
Check(PreviewPlanner.IsComplete(previews) && PreviewPlanner.Missing(previews) == 0, "preview completes only after all arrivals");
Console.WriteLine("Story core checks passed; these do not validate game integration or saves.");
